import esbuild from "esbuild";
import process from "process";
import fs from "fs";
import path from "path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
GraphPro-Next: Next-Generation High-Performance Graph Layout & Selection for Obsidian
High-Performance Graph Suite (Apache-2.0 License)
*/
`;

const prod = process.argv[2] === "production";
const vaultPluginDir = "/mnt/e/SynologyDrive/Obsidian/.obsidian/plugins/graph-pro-next";

function copyToVault() {
  try {
    if (!fs.existsSync(vaultPluginDir)) {
      fs.mkdirSync(vaultPluginDir, { recursive: true });
    }
    const files = ["main.js", "manifest.json", "styles.css"];
    for (const f of files) {
      if (fs.existsSync(f)) {
        fs.copyFileSync(f, path.join(vaultPluginDir, f));
      }
    }
    console.log(`[Build] Successfully synced to Obsidian vault: ${vaultPluginDir}`);
  } catch (err) {
    console.error("[Build] Error copying to vault:", err);
  }
}

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
  ],
  format: "cjs",
  target: "es2022",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
});

if (prod) {
  await context.rebuild();
  copyToVault();
  process.exit(0);
} else {
  await context.watch();
  copyToVault();
}
